// Turns course/torchlite.py into the files of a `torch` package, so that
// `import torch.nn as nn`, `import torch.nn.functional as F`, `torch.optim` and
// `from torch.utils.data import DataLoader` all work. Used by build.js and the tests.
const fs = require("fs");
const path = require("path");
function torchFiles(root) {
  const src = fs.readFileSync(path.join(root, "course", "torchlite.py"), "utf8");
  const nnNames = ["Module", "Linear", "Embedding", "LayerNorm", "Dropout", "ReLU", "Sigmoid", "Tanh", "Softmax",
    "Sequential", "ModuleList", "Parameter", "CrossEntropyLoss", "MSELoss", "BCELoss", "BCEWithLogitsLoss"];
  return {
    "torch/__init__.py": src,
    "torch/nn/__init__.py": "from torch import " + nnNames.join(", ") + "\nfrom torch.nn import functional\n",
    "torch/nn/functional.py": "from torch import F as _F\n" +
      ["relu", "sigmoid", "tanh", "softmax", "log_softmax", "cross_entropy", "mse_loss", "binary_cross_entropy", "binary_cross_entropy_with_logits"]
        .map(n => n + " = _F." + n).join("\n") + "\n",
    "torch/optim.py": "from torch import SGD, Adam, Optimizer\n",
    "torch/utils/__init__.py": "from torch.utils import data\n",
    "torch/utils/data.py": "from torch import Dataset, DataLoader, TensorDataset\n",
  };
}
// course/torchlite.js: the same files as a JS object the browser writes into Pyodide.
function torchDataJs(root) {
  return "// Generated by build.js from course/torchlite.py. Do not edit by hand.\nconst TORCH_FILES = " +
    JSON.stringify(torchFiles(root), null, 0) + ";\n";
}
module.exports = { torchFiles, torchDataJs };
